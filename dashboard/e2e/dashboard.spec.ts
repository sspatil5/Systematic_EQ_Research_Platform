import { expect, test } from '@playwright/test'

test('overview agrees with stored API metrics and date/sample filters work', async ({ page, request }) => {
  const errors:string[]=[]
  page.on('pageerror',e => errors.push(e.message))
  const source=await (await request.get('/api/backtest')).json()
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Research overview'})).toBeVisible()
  await expect(page.locator('.metric-value').first()).toHaveText(`${(source.metrics.cagr*100).toFixed(2)}%`)
  await page.screenshot({path:'test-results/overview-desktop.png',fullPage:true})
  await page.getByLabel('Research period').selectOption('CONFIRMATION')
  const confirm=await (await request.get('/api/backtest?period=CONFIRMATION')).json()
  await expect(page.locator('.metric-value').first()).toHaveText(`${(confirm.metrics.cagr*100).toFixed(2)}%`)
  await page.getByRole('button',{name:'Date range'}).click()
  await page.getByLabel('Start date',{exact:true}).fill('2024-01-01')
  await page.getByLabel('End date',{exact:true}).fill('2024-12-31')
  await page.getByRole('button',{name:'Apply dates'}).click()
  const filtered=await (await request.get('/api/backtest?period=CONFIRMATION&start=2024-01-01&end=2024-12-31')).json()
  await expect(page.locator('.metric-value').first()).toHaveText(`${(filtered.metrics.cagr*100).toFixed(2)}%`)
  expect(errors).toEqual([])
})

test('universe searches source data and preserves Bloomberg failures', async ({page}) => {
  await page.goto('/#universe')
  await expect(page.getByRole('heading',{name:'Data & universe'})).toBeVisible()
  await page.getByLabel('Search tickers').fill('AAPL')
  await expect(page.getByRole('cell').filter({hasText:/^AAAAPL$/})).toBeVisible()
  await expect(page.locator('.table-footer')).toContainText('1 of 1 records')
  await page.getByRole('button',{name:/Bloomberg importer/}).click()
  await expect(page.getByRole('heading',{name:'Security-master import failed'})).toBeVisible()
  await expect(page.getByText(/missing Primary Exchange MIC/).first()).toBeVisible()
})

test('signals, backtests, reports and run controls render real outputs', async ({page}) => {
  const errors:string[]=[]
  page.on('pageerror',e => errors.push(e.message))
  await page.goto('/#signals')
  await expect(page.getByRole('heading',{name:'Signal scorecard'})).toBeVisible()
  await page.getByLabel('Selected signal').selectOption('momentum_12_1')
  await expect(page.getByRole('heading',{name:'Daily information coefficient'})).toBeVisible()
  await page.getByRole('link',{name:'Backtest results',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Monthly returns',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Run configuration',exact:true}).click()
  await expect(page.getByText('Current reference YAML; original machine-readable run snapshot unavailable.')).toBeVisible()
  await page.getByRole('link',{name:'Reports & audit',exact:true}).click()
  await page.getByLabel('Search artifacts').fill('research_freeze.md')
  await page.getByText('research_freeze.md',{exact:true}).click()
  await expect(page.locator('.document-preview')).toContainText('Phase 4 research freeze')
  await page.getByRole('button',{name:'Check integrity'}).click()
  await expect(page.locator('.integrity-result')).toContainText('unrecorded')
  await page.getByRole('link',{name:'Runs & configuration',exact:true}).click()
  await expect(page.getByRole('button',{name:'Launch new run'})).toBeEnabled()
  await page.getByLabel('Pipeline stage').selectOption('bloomberg-import')
  await expect(page.getByRole('button',{name:'Launch new run'})).toBeDisabled()
  await page.getByLabel('Bloomberg snapshot date').fill('2026-08-24')
  await expect(page.getByRole('button',{name:'Launch new run'})).toBeEnabled()
  expect(errors).toEqual([])
})

test('mobile navigation and empty dates remain usable', async ({page}) => {
  await page.setViewportSize({width:390,height:844})
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Research overview'})).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({path:'test-results/overview-mobile.png',fullPage:true})
  await page.getByRole('button',{name:'Open navigation'}).click()
  await page.getByRole('link',{name:'Backtest results',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Backtest results',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Date range'}).click()
  await page.getByLabel('Start date',{exact:true}).fill('2035-01-01')
  await page.getByRole('button',{name:'Apply dates'}).click()
  await expect(page.getByRole('heading',{name:'No backtest output in this context'})).toBeVisible()
})
